#!/usr/bin/env node
// Regenerates packages/shared-types/src/catalogueReferences.ts from data/services.json.
//
//   npm run catalogue:refs
//
// The Negotiator scores each candidate against fixed reference values for its category
// (the best and worst price, uptime and latency in the whole catalogue), so a score means
// the same thing whichever other candidates happen to be present. Those values are
// derived here from the same file that seeds MongoDB and Qdrant. A test in
// evaluation/src/ground-truth.test.ts fails if this output and the catalogue drift apart.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const services = JSON.parse(readFileSync(join(root, "data", "services.json"), "utf-8"));

const refs = {};
for (const s of services) {
  const r = (refs[s.capability] ??= {
    price: { min: s.price, max: s.price },
    uptime: { min: s.uptime, max: s.uptime },
    latencyMs: { min: s.latencyMs, max: s.latencyMs },
  });
  r.price = { min: Math.min(r.price.min, s.price), max: Math.max(r.price.max, s.price) };
  r.uptime = { min: Math.min(r.uptime.min, s.uptime), max: Math.max(r.uptime.max, s.uptime) };
  r.latencyMs = { min: Math.min(r.latencyMs.min, s.latencyMs), max: Math.max(r.latencyMs.max, s.latencyMs) };
}

const sorted = Object.fromEntries(Object.keys(refs).sort().map((k) => [k, refs[k]]));
const body = `// Generated by scripts/catalogue-references.mjs from data/services.json. Do not edit by hand;
// run "npm run catalogue:refs" after changing the catalogue.

export interface Range {
  min: number;
  max: number;
}

export interface CategoryReferences {
  price: Range;
  uptime: Range;
  latencyMs: Range;
}

export const CATALOGUE_REFERENCES: Record<string, CategoryReferences> = ${JSON.stringify(sorted, null, 2)};
`;

const out = join(root, "packages", "shared-types", "src", "catalogueReferences.ts");
writeFileSync(out, body);
console.log(`Wrote ${Object.keys(sorted).length} categories to ${out}`);
