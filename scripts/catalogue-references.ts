#!/usr/bin/env tsx
// Regenerates packages/shared-types/src/catalogueReferences.ts.
//
//   npm run catalogue:refs
//
// The Negotiator scores each candidate against fixed reference values for its category
// (the best and worst price, uptime and latency in the whole catalogue), so a score means
// the same thing whichever other candidates happen to be present. Two tables are written:
//
//   CATALOGUE_REFERENCES       from data/services.json (the 21 synthetic services), used by
//                              the offline evaluation and the unit tests
//   LIVE_CATALOGUE_REFERENCES  from the real services in data/services.v2.json, projected
//                              with toV1 exactly as seed-services --v2 writes them to MongoDB,
//                              used by the live Lambda (SAGE_CATALOGUE=v2). WP3.5 L6.
//
// Tests in evaluation/src/ground-truth.test.ts fail if either table and its source drift apart.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { toV1, type CatalogueServiceV2 } from "../packages/catalogue/src";

interface Row { capability: string; price: number; uptime: number; latencyMs?: number }
type Range = { min: number; max: number };
type Refs = Record<string, { price: Range; uptime: Range; latencyMs: Range }>;

const root = join(__dirname, "..");

function widen(r: Range | undefined, v: number): Range {
  return r ? { min: Math.min(r.min, v), max: Math.max(r.max, v) } : { min: v, max: v };
}

function build(rows: Row[]): Refs {
  const acc: Record<string, { price?: Range; uptime?: Range; latencyMs?: Range }> = {};
  for (const s of rows) {
    const r = (acc[s.capability] ??= {});
    r.price = widen(r.price, s.price);
    r.uptime = widen(r.uptime, s.uptime);
    if (typeof s.latencyMs === "number") r.latencyMs = widen(r.latencyMs, s.latencyMs);
  }
  // A category with no latency figures gets a neutral range (best === worst scores 1).
  return Object.fromEntries(
    Object.keys(acc)
      .sort()
      .map((k) => [k, { price: acc[k].price!, uptime: acc[k].uptime!, latencyMs: acc[k].latencyMs ?? { min: 0, max: 0 } }])
  );
}

const v1: Row[] = JSON.parse(readFileSync(join(root, "data", "services.json"), "utf-8"));
const v2: CatalogueServiceV2[] = JSON.parse(readFileSync(join(root, "data", "services.v2.json"), "utf-8"));
const live: Row[] = v2.filter((s) => !s.synthetic).map(toV1);

const synthetic = build(v1);
const real = build(live);

const body = `// Generated by scripts/catalogue-references.ts from data/services.json and data/services.v2.json.
// Do not edit by hand; run "npm run catalogue:refs" after changing either catalogue.

export interface Range {
  min: number;
  max: number;
}

export interface CategoryReferences {
  price: Range;
  uptime: Range;
  latencyMs: Range;
}

// The 21 synthetic services: offline evaluation and unit tests.
export const CATALOGUE_REFERENCES: Record<string, CategoryReferences> = ${JSON.stringify(synthetic, null, 2)};

// The real services as seeded live (estimated USD/month prices, blended QoS).
export const LIVE_CATALOGUE_REFERENCES: Record<string, CategoryReferences> = ${JSON.stringify(real, null, 2)};

// The live Lambda sets SAGE_CATALOGUE=v2; everything else keeps the synthetic table.
export function referencesFor(category: string): CategoryReferences | undefined {
  const table = process.env.SAGE_CATALOGUE === "v2" ? LIVE_CATALOGUE_REFERENCES : CATALOGUE_REFERENCES;
  return table[category];
}
`;

const out = join(root, "packages", "shared-types", "src", "catalogueReferences.ts");
writeFileSync(out, body);
console.log(`Wrote ${Object.keys(synthetic).length} synthetic and ${Object.keys(real).length} live categories to ${out}`);
